// Select sparse illustrative storm complexes inside the actual optical cloud
// atlas. This is a reproducible art preset, not inferred meteorological data.
import sharp from 'sharp';
import {writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const {data,info}=await sharp('public/media/orbit/earth-clouds-nasa-4096.avif').removeAlpha().raw().toBuffer({resolveWithObject:true});
const random=n=>{const x=Math.sin(n*127.1+311.7)*43758.5453;return x-Math.floor(x);};
const norm=p=>{const l=Math.hypot(...p);return p.map(v=>v/l);};
const dot=(a,b)=>a.reduce((v,x,i)=>v+x*b[i],0);
const coverage=p=>{
 const u=Math.atan2(p[1],p[0])/(2*Math.PI)+.5,v=.5-Math.asin(p[2])/Math.PI;
 const x=Math.floor(u*info.width)%info.width,y=Math.min(info.height-1,Math.floor(v*info.height));
 return data[(y*info.width+x)*info.channels]/255;
};
const regions=[];
for(let i=0;i<100000&&regions.length<64;i++){
 const z=(random(i*11+1)*2-1)*.82,a=random(i*11+2)*Math.PI*2,r=Math.sqrt(1-z*z);
 const n=[r*Math.cos(a),r*Math.sin(a),z];
 if(coverage(n)<.78||regions.some(g=>dot(g[0],n)>Math.cos(600/6371)))continue;
 const east=[-Math.sin(a),Math.cos(a),0],north=[-z*Math.cos(a),-z*Math.sin(a),r];
 const angle=random(i*11+3)*Math.PI,axis=east.map((v,k)=>v*Math.cos(angle)+north[k]*Math.sin(angle));
 const side=east.map((v,k)=>-v*Math.sin(angle)+north[k]*Math.cos(angle));
 const cells=[];
 for(let k=0;k<5;k++){
  const along=(k-2)*35,across=(random(i*31+k)*2-1)*12;
  const p=norm(n.map((v,j)=>v+(axis[j]*along+side[j]*across)/6371));
  // A dense center alone is insufficient: require a surrounding cloud body.
  const probes=[p,...[east,north].flatMap(dir=>[-1,1].map(sign=>norm(p.map((v,j)=>v+dir[j]*sign*12/6371))))];
  if(coverage(p)>=.78&&Math.min(...probes.map(coverage))>=.64)cells.push(p);
 }
 if(cells.length>=3)regions.push(cells);
}
if(regions.length!==64)throw Error(`Only ${regions.length} storm regions found`);
const digest=createHash('sha256').update(data).digest('hex');
await writeFile('src/scripts/storm-regions.ts',`// Generated by scripts/prepare-storm-regions.mjs; cloud atlas pixels SHA256 ${digest}.\n// Sparse selected cloud complexes, NOT a live weather or lightning dataset.\nexport const stormRegions:number[][][]=[\n${regions.map(g=>JSON.stringify(g.map(p=>p.map(v=>+v.toFixed(8))))).join(",\n")}\n];\n`);
console.log({regions:regions.length,cells:regions.flat().length});
