// The HUD's small globe: a 128 × 64 land mask, one bit per cell, from the water
// channel of the packed terrain map (Natural Earth 1:10m land, public domain).
// Rows run south to north, columns west to east from 180° W, as in the map.
import {readFileSync,writeFileSync} from 'node:fs';
import {gunzipSync} from 'node:zlib';
import {decodeTerrain} from '../src/scripts/earth-terrain.ts';

const raw=gunzipSync(readFileSync(new URL('../public/media/orbit/earth-terrain-4096.dem',import.meta.url)));
const {levels}=decodeTerrain(raw.buffer.slice(raw.byteOffset,raw.byteOffset+raw.byteLength));
const level=levels.find(l=>l.width===128);
if(!level)throw Error('No 128-wide terrain level');
const {width,height,data}=level,bits=new Uint8Array(width*height/8);
let land=0;
for(let i=0;i<width*height;i++)if(data[i*3+2]<128){bits[i>>3]|=1<<(i&7);land++;}
const target=new URL('../src/scripts/globe-land.ts',import.meta.url);
writeFileSync(target,`// Generated by scripts/build-globe-land.mjs: a ${width} × ${height} land mask for the
// HUD's small globe, from the terrain map's water channel (Natural Earth 1:10m
// land, public domain). One bit per cell, rows south to north, columns west to
// east from 180° W.
export const GLOBE_LAND={width:${width},height:${height},bits:'${Buffer.from(bits).toString('base64')}'};
`);
console.log(target.pathname,`${(land/(width*height)*100).toFixed(1)}% land`,bits.length,'bytes');
